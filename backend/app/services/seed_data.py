async def seed_donors_if_empty():
    """Seeds the initial 20 synthetic donors if the donor collection is empty."""
    db = get_db()
    count = await db.donors.count_documents({})
    if count == 0:
        logger.info("[SEED] Seeding 20 realistic synthetic donors for academic demonstration...")
        now = datetime.now(timezone.utc)
        docs_to_insert = []
        for d in INITIAL_DONORS:
            item = dict(d)
            item["created_at"] = now
            item["updated_at"] = now
            docs_to_insert.append(item)
        await db.donors.insert_many(docs_to_insert)
        logger.info(f"[SEED] Successfully seeded {len(docs_to_insert)} donors.")
        return len(docs_to_insert)
    else:
        logger.info(f"[SEED] Donors collection already contains {count} records. Skipping auto-seed.")
        return count
